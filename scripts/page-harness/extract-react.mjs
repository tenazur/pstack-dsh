/**
 * Pull React 18 and react-dom out of the shell's own bundle into a plain script.
 *
 * Why this exists: the unit tests render the page with a hook stub, which cannot show a layout bug —
 * an overflowing select, a chip whose label never rendered, a card that does not look like the
 * shell's. A browser can, and `scripts/check-page-layout.mjs` uses one; but nothing on this machine
 * ships a standalone React build, while the GUI's own bundle contains one, minified and inlined.
 * This cuts the two factories out of it verbatim, so the harness renders with the exact React the
 * GUI ships.
 *
 * The output is **generated, not committed**: it is third-party code, and the file it is cut from is
 * on every machine that runs the GUI. Regenerate it whenever the DSH version changes, which is also
 * when the shell's markup could have moved under this page.
 *
 *   node scripts/page-harness/extract-react.mjs   # writes scripts/page-harness/react-from-shell.js
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

// The shell's bundled entry, found by glob rather than by a hashed name that changes every release.
const ASSETS = '/usr/lib/node_modules/@deepseek-ai/dsh/node_modules/@deepseek-ai/dsh-web-frontend/dist/assets'
const entry = readdirSync(ASSETS).filter((name) => /^index-.*\.js$/.test(name)).sort()[0]
if (entry === undefined) throw new Error(`no shell bundle in ${ASSETS}; is DeepSeek Harness installed?`)
const src = readFileSync(join(ASSETS, entry), 'utf8')

/** A top-level function declaration, by brace counting. */
function block(name) {
  const start = src.indexOf(`function ${name}(`)
  if (start < 0) throw new Error(`no function ${name} in the shell bundle`)
  let depth = 0
  for (let pos = src.indexOf('{', start); pos < src.length; pos += 1) {
    if (src[pos] === '{') depth += 1
    else if (src[pos] === '}') {
      depth -= 1
      if (depth === 0) return src.slice(start, pos + 1)
    }
  }
  throw new Error(`function ${name} never closes`)
}

const reactDom = [
  block('$r'), // the __esModule unwrapper the shell's React namespace is built with
  block('Eo'), // the namespace combinator
  src.slice(src.indexOf('var V0={exports:{}},ve={};'), src.indexOf('function Xa()')),
  block('Xa'),
  'var i5;',
  block('P3'),
].join('\n')

const dom = [
  src.slice(src.indexOf('var A0={exports:{}},Lr={};'), src.indexOf('function oc()')),
  'var a5;',
  block('oc'),
  'var l5;',
  block('sc'),
  block('lc'),
  'var c5, u5, Z0={};',
].join('\n')

const out = `// Generated by scripts/page-harness/extract-react.mjs — React 18.3.1 and react-dom, cut from the
// shell bundle the GUI itself loads. Do not edit by hand.
${reactDom}
${dom}
window.__REACT__ = P3()
window.__REACT_DOM__ = lc()
`
const target = new URL('react-from-shell.js', import.meta.url)
writeFileSync(target, out)
console.log(`wrote ${target.pathname} (${String(out.length)} bytes) from ${entry}`)
